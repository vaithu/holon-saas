package com.holonplatform.multitenant.onboarding.internal;

import com.holonplatform.multitenant.FrameworkReservedTableNames;
import com.holonplatform.multitenant.data.DatabaseDialect;
import com.holonplatform.multitenant.data.SchemaInitSqlProvider;
import com.holonplatform.multitenant.data.SchemaNameResolver;
import com.holonplatform.multitenant.data.TenantDataSourceRegistry;
import com.holonplatform.multitenant.data.datasource.BoundedTenantDataSourceRegistry;
import com.holonplatform.multitenant.data.datasource.SchemaPerTenantDataSourceProvider;
import com.holonplatform.multitenant.data.migration.TenantSchemaInitializer;
import org.junit.jupiter.api.Test;
import org.testcontainers.postgresql.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

import java.sql.Connection;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.*;

/**
 * Real Testcontainers-backed regression test proving the framework's bundled
 * {@code V1__}/{@code V1.1__} tenant-migration scripts and {@link DatabaseDialect} schema-switch
 * SQL actually work against a real PostgreSQL server — not just H2, the only dialect ever
 * empirically exercised end-to-end anywhere in this codebase before this test existed (see
 * {@link TenantBaselineMigrationScriptTest}). {@link DatabaseDialect#POSTGRESQL} was previously
 * verified only at the string-assertion level ({@code DatabaseDialectTest}), never by actually
 * running the generated SQL against the real database engine it targets — a real gap, since
 * dialect-specific SQL syntax/identifier-quoting mistakes cannot be caught any other way.
 *
 * <h2>Why MySQL isn't covered here</h2>
 * <p>This test originally also covered MySQL. Running it for the first time against a real
 * MySQL server revealed that the shared migration scripts use syntax MySQL doesn't support
 * ({@code BIGSERIAL}, {@code GENERATED BY DEFAULT AS IDENTITY} — MySQL only understands
 * {@code AUTO_INCREMENT}) across 6 tables, including several actively used by the framework
 * itself ({@code tenant_users}, {@code audit_entries}, {@code tenant_permissions}, ...). Rather
 * than a piecemeal fix, {@code MYSQL} was removed from {@link DatabaseDialect} entirely — see
 * that enum's Javadoc for the full rationale and what a proper fix would require.
 *
 * <p>Requires a running Docker daemon (via Testcontainers) — {@code @Testcontainers(disabledWithoutDocker = true)}
 * automatically skips this entire class (not a failure) when Docker isn't available, so
 * {@code mvn install} still succeeds on machines/CI runners without Docker; the real dialect
 * coverage only kicks in where Docker is present. SQL Server and Oracle are not covered here —
 * their official container images are either license-gated (Oracle) or require accepting an
 * EULA (SQL Server).
 */
@Testcontainers(disabledWithoutDocker = true)
class TenantMigrationScriptsPostgresTest {

	@Container
	static PostgreSQLContainer postgres = new PostgreSQLContainer("postgres:16-alpine");

	@Test
	void v1AndV1_1Scripts_applyCleanly_onRealPostgres() throws Exception {
		SchemaNameResolver schemaNameResolver = SchemaNameResolver.withPrefix("tenant_");
		SchemaInitSqlProvider initSqlProvider = SchemaInitSqlProvider.forDialect(DatabaseDialect.POSTGRESQL);

		SchemaPerTenantDataSourceProvider provider = new SchemaPerTenantDataSourceProvider(
				postgres.getJdbcUrl(), postgres.getUsername(), postgres.getPassword(),
				schemaNameResolver, initSqlProvider);

		try (TenantDataSourceRegistry registry = new BoundedTenantDataSourceRegistry(provider, 10)) {
			TenantSchemaInitializer initializer = new TenantSchemaInitializer(registry, schemaNameResolver);
			initializer.setDialect(DatabaseDialect.POSTGRESQL);
			initializer.setAutoCreateSchema(true);
			// Default migrationLocations ("classpath:db/tenant-migration") already points at
			// the real, bundled V1__/V1.1__ scripts — intentionally not overridden here, exactly
			// like TenantBaselineMigrationScriptTest's H2-based equivalent.

			assertThatCode(() -> initializer.migrate("acme")).doesNotThrowAnyException();

			try (Connection connection = registry.getDataSource("acme").getConnection();
					Statement statement = connection.createStatement()) {
				// FrameworkReservedTableNames.ALL is kept mechanically in sync with these same
				// scripts by FrameworkReservedTableNamesSyncTest — reusing it here means this
				// test automatically covers any table added/renamed in the future with zero
				// changes needed.
				for (String table : FrameworkReservedTableNames.ALL) {
					assertThatCode(() -> statement.execute("SELECT COUNT(*) FROM " + table))
							.as("table " + table + " should be queryable on PostgreSQL")
							.doesNotThrowAnyException();
				}
			}
		}
	}
}
