-- ============================================================
-- V1.1__tenant_framework_module_tables.sql
--
-- Framework-level baseline tables for the optional holon-saas modules
-- (tenant-users, tenant-audit, tenant-billing, tenant-invitations,
-- tenant-whatsapp, tenant-permissions, tenant-settings), created in every
-- tenant schema by the automatic onboarding process.
--
-- Versioned "1.1" (not "2") deliberately: consuming applications commonly
-- reserve V002 onward for their own tenant-schema tables (this is exactly
-- what crm-minimal does — see its db/tenant-migration/V002.. V047 scripts).
-- Flyway normalizes "V2" and "V002" to the same version identifier, so a
-- framework script versioned "2" would collide with any such app. "1.1"
-- sorts immediately after V1 (this module's own baseline) and before any
-- V2+ application script, without colliding with either.
--
-- Table/column names and types mirror each module's JPA entity exactly
-- (@Table/@Column names, unquoted) so Hibernate's own generated SQL and
-- this hand-written DDL fold identifier case identically on every dialect
-- without needing to match Flyway's own schema-identifier quoting (that
-- concern only applies to the SCHEMA name itself, not table/column names
-- within it — see DatabaseDialect's javadoc for that unrelated issue).
--
-- These tables are managed by the Holon multi-tenant framework. Consuming
-- applications should number their own scripts V2__ and higher.
-- ============================================================

-- ── tenant-users ────────────────────────────────────────────────────────
-- Mirrors com.holonplatform.multitenant.users.TenantUser
CREATE TABLE IF NOT EXISTS tenant_users (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        VARCHAR(255)  NOT NULL,
    tenant_id      VARCHAR(255)  NOT NULL,
    email          VARCHAR(255)  NOT NULL,
    display_name   VARCHAR(255),
    role           VARCHAR(255)  NOT NULL,
    status         VARCHAR(255)  NOT NULL,
    created_at     TIMESTAMP     NOT NULL,
    last_login_at  TIMESTAMP,
    -- Arbitrary key-value metadata (TenantUser#attributes), stored as a single JSON text
    -- column rather than a separate @ElementCollection join table: Holon's BeanDatastoreHelper
    -- always projects the whole bean in one query, referencing collection-valued properties
    -- directly in the JPQL SELECT list, which Hibernate always translates to an INNER JOIN
    -- against the collection table. Whenever the map is empty (the common case), that inner
    -- join has no matching row and silently drops the ENTIRE parent row from every query
    -- result. A single JSON column has no second table to join against, so this can't happen.
    attributes     TEXT          NOT NULL DEFAULT '{}',
    CONSTRAINT uq_tenant_email UNIQUE (tenant_id, email)
);
CREATE INDEX IF NOT EXISTS idx_tenant_user        ON tenant_users (tenant_id, user_id);
CREATE INDEX IF NOT EXISTS idx_tenant_email       ON tenant_users (tenant_id, email);
CREATE INDEX IF NOT EXISTS idx_user_status        ON tenant_users (user_id, status);

-- ── tenant-audit ────────────────────────────────────────────────────────
-- Mirrors com.holonplatform.multitenant.audit.AuditEntry
CREATE TABLE IF NOT EXISTS audit_entries (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     VARCHAR(255)  NOT NULL,
    action        VARCHAR(255)  NOT NULL,
    actor         VARCHAR(255)  NOT NULL,
    resource_type VARCHAR(100),
    resource_id   VARCHAR(255),
    description   TEXT,
    ip_address    VARCHAR(100),
    severity      VARCHAR(255)  NOT NULL,
    created_at    TIMESTAMP     NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_tenant_created ON audit_entries (tenant_id, created_at);
CREATE INDEX IF NOT EXISTS idx_tenant_action  ON audit_entries (tenant_id, action);

-- ── tenant-billing ──────────────────────────────────────────────────────
-- Mirrors com.holonplatform.multitenant.billing.Invoice.
-- Table deliberately prefixed "tenant_billing_" (not the bare "INVOICE" this
-- entity used before) — "invoice"/"subscription" are extremely common ERP/
-- CRM domain terms that any real consuming application is likely to also
-- want for its own business data (e.g. crm-minimal's own customer-facing
-- invoice_table/subscription_table migrations, for invoicing THIS tenant's
-- customers — a completely different concept from this platform billing
-- THE TENANT for their subscription to use the platform itself). A bare,
-- unprefixed name collides directly with exactly that kind of app table.
CREATE TABLE IF NOT EXISTS tenant_billing_invoice (
    INVOICE_ID   VARCHAR(100)   NOT NULL PRIMARY KEY,
    TENANT_ID    VARCHAR(100)   NOT NULL,
    AMOUNT_DUE   DECIMAL(12,2)  NOT NULL,
    CURRENCY     VARCHAR(3)     NOT NULL,
    STATUS       VARCHAR(50)    NOT NULL,
    ISSUED_AT    TIMESTAMP      NOT NULL,
    PAID_AT      TIMESTAMP,
    EXTERNAL_REF VARCHAR(255)
);
CREATE INDEX IF NOT EXISTS idx_tenant_billing_invoice_tenant ON tenant_billing_invoice (TENANT_ID);
CREATE INDEX IF NOT EXISTS idx_tenant_billing_invoice_issued ON tenant_billing_invoice (ISSUED_AT);

-- Mirrors com.holonplatform.multitenant.billing.Subscription — see naming
-- rationale above.
CREATE TABLE IF NOT EXISTS tenant_billing_subscription (
    TENANT_ID    VARCHAR(100)  NOT NULL PRIMARY KEY,
    PLAN         VARCHAR(50)   NOT NULL,
    STATUS       VARCHAR(50)   NOT NULL,
    PERIOD_START TIMESTAMP,
    PERIOD_END   TIMESTAMP,
    TRIAL_END    TIMESTAMP,
    CANCELLED_AT TIMESTAMP,
    EXTERNAL_REF VARCHAR(255)
);
CREATE INDEX IF NOT EXISTS idx_tenant_billing_subscription_status ON tenant_billing_subscription (STATUS);

-- ── tenant-invitations ──────────────────────────────────────────────────
-- Mirrors com.holonplatform.multitenant.invitations.UserInvitation
CREATE TABLE IF NOT EXISTS user_invitation (
    token              VARCHAR(64)   NOT NULL PRIMARY KEY,
    tenant_id          VARCHAR(64)   NOT NULL,
    email              VARCHAR(255)  NOT NULL,
    invited_by_user_id VARCHAR(255),
    platform_role      VARCHAR(32)   NOT NULL,
    job_role           VARCHAR(100),
    status             VARCHAR(32)   NOT NULL,
    created_at         TIMESTAMP     NOT NULL,
    expires_at         TIMESTAMP     NOT NULL,
    accepted_at        TIMESTAMP,
    -- Arbitrary key-value metadata (UserInvitation#attributes) — single JSON text column;
    -- see the identical comment on tenant_users.attributes above for why this replaced a
    -- separate @ElementCollection join table (inner-join-drops-empty-parent-row bug).
    attributes         TEXT          NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS idx_invitation_tenant ON user_invitation (tenant_id);
CREATE INDEX IF NOT EXISTS idx_invitation_email  ON user_invitation (email);

-- ── tenant-whatsapp ─────────────────────────────────────────────────────
-- Mirrors com.holonplatform.multitenant.whatsapp.WhatsAppConversation
CREATE TABLE IF NOT EXISTS whatsapp_conversation (
    window_key     VARCHAR(128)  NOT NULL PRIMARY KEY,
    tenant_id      VARCHAR(64)   NOT NULL,
    customer_phone VARCHAR(32)   NOT NULL,
    type           VARCHAR(32)   NOT NULL,
    opened_at      TIMESTAMP     NOT NULL,
    expires_at     TIMESTAMP     NOT NULL,
    message_count  INT           NOT NULL,
    charged        BOOLEAN       NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_whatsapp_conversation_tenant         ON whatsapp_conversation (tenant_id);
CREATE INDEX IF NOT EXISTS idx_whatsapp_conversation_tenant_expires ON whatsapp_conversation (tenant_id, expires_at);

-- Mirrors com.holonplatform.multitenant.whatsapp.WhatsAppMessage
CREATE TABLE IF NOT EXISTS whatsapp_message (
    local_id          VARCHAR(64)   NOT NULL PRIMARY KEY,
    message_id        VARCHAR(128),
    tenant_id         VARCHAR(64)   NOT NULL,
    to_phone          VARCHAR(32)   NOT NULL,
    from_phone        VARCHAR(32),
    type              VARCHAR(32)   NOT NULL,
    conversation_type VARCHAR(32)   NOT NULL,
    content           TEXT,
    template_name     VARCHAR(255),
    -- Template variable substitutions (WhatsAppMessage#templateParams) — single JSON text
    -- column; see the identical comment on tenant_users.attributes above for why this
    -- replaced a separate @ElementCollection join table (inner-join-drops-empty-parent-row
    -- bug — a message with no template params would otherwise vanish from every query).
    template_params   TEXT          NOT NULL DEFAULT '{}',
    status            VARCHAR(32)   NOT NULL,
    created_at        TIMESTAMP     NOT NULL,
    sent_at           TIMESTAMP,
    delivered_at      TIMESTAMP,
    read_at           TIMESTAMP,
    free_conversation BOOLEAN       NOT NULL,
    error_code        VARCHAR(64),
    error_message     TEXT
);
CREATE INDEX IF NOT EXISTS idx_whatsapp_message_tenant         ON whatsapp_message (tenant_id);
CREATE INDEX IF NOT EXISTS idx_whatsapp_message_tenant_created ON whatsapp_message (tenant_id, created_at);
CREATE INDEX IF NOT EXISTS idx_whatsapp_message_message_id     ON whatsapp_message (message_id);
CREATE INDEX IF NOT EXISTS idx_whatsapp_message_tenant_to      ON whatsapp_message (tenant_id, to_phone);
CREATE INDEX IF NOT EXISTS idx_whatsapp_message_tenant_from    ON whatsapp_message (tenant_id, from_phone);

-- ── tenant-permissions ──────────────────────────────────────────────────
-- Mirrors com.holonplatform.multitenant.permissions.internal.PermissionEntity.
-- NOTE: tenantId/createdAt have no explicit @Column(name=...), so Spring
-- Boot's default SpringPhysicalNamingStrategy converts them to snake_case
-- (tenant_id / created_at) — verified against every other unnamed @Column
-- in this same file (AuditEntry.tenantId/createdAt follow the identical rule).
CREATE TABLE IF NOT EXISTS tenant_permissions (
    id         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  VARCHAR(255)  NOT NULL,
    role_name  VARCHAR(100)  NOT NULL,
    permission VARCHAR(255)  NOT NULL,
    created_at TIMESTAMP     NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_permission_tenant      ON tenant_permissions (tenant_id);
CREATE INDEX IF NOT EXISTS idx_permission_tenant_role ON tenant_permissions (tenant_id, role_name);
CREATE UNIQUE INDEX IF NOT EXISTS idx_permission_uq   ON tenant_permissions (tenant_id, role_name, permission);

-- Mirrors com.holonplatform.multitenant.permissions.internal.TenantPermissionOverrideEntity
CREATE TABLE IF NOT EXISTS tenant_permission_overrides (
    id         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  VARCHAR(255)  NOT NULL,
    role_name  VARCHAR(100)  NOT NULL,
    view_id    VARCHAR(100)  NOT NULL,
    action     VARCHAR(50)   NOT NULL,
    allowed    BOOLEAN       NOT NULL,
    created_at TIMESTAMP     NOT NULL,
    updated_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_perm_override_tenant ON tenant_permission_overrides (tenant_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_perm_override_lookup ON tenant_permission_overrides (tenant_id, role_name, view_id, action);

-- Mirrors com.holonplatform.multitenant.permissions.internal.TenantCustomRoleEntity
CREATE TABLE IF NOT EXISTS tenant_custom_roles (
    id           BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    VARCHAR(255)  NOT NULL,
    role_name    VARCHAR(100)  NOT NULL,
    display_name VARCHAR(150),
    description  VARCHAR(500),
    base_role    VARCHAR(100),
    created_at   TIMESTAMP     NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_custom_role_tenant ON tenant_custom_roles (tenant_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_custom_role_lookup ON tenant_custom_roles (tenant_id, role_name);

-- ── tenant-settings ─────────────────────────────────────────────────────
-- Mirrors com.holonplatform.multitenant.settings.TenantSettingOverride
CREATE TABLE IF NOT EXISTS tenant_setting_override (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     VARCHAR(255)  NOT NULL,
    setting_key   VARCHAR(255)  NOT NULL,
    setting_value TEXT,
    CONSTRAINT uq_tenant_setting_override_key UNIQUE (tenant_id, setting_key)
);
CREATE INDEX IF NOT EXISTS idx_tenant_setting_override_tenant_id ON tenant_setting_override (tenant_id);

-- Mirrors com.holonplatform.multitenant.settings.TenantPlanSettingDefault
-- (plan-level, not tenant-specific data — created here too since the service
-- queries it through the same tenant-scoped Datastore/schema as everything
-- else; expect this table to be empty in each tenant schema unless plan
-- defaults are explicitly seeded per-tenant).
CREATE TABLE IF NOT EXISTS tenant_plan_setting_default (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan          VARCHAR(50)   NOT NULL,
    setting_key   VARCHAR(255)  NOT NULL,
    setting_value TEXT,
    CONSTRAINT uq_tenant_plan_setting_default_key UNIQUE (plan, setting_key)
);
