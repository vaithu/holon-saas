package com.holonplatform.multitenant.data;

import java.util.Optional;

/**
 * Represents the SQL dialect variants that require different commands to switch
 * the active schema within a connection.
 *
 * <p>Used by {@link SchemaInitSqlProvider} to generate the appropriate
 * connection initialisation SQL for each tenant's connection pool, and by
 * {@link com.holonplatform.multitenant.data.migration.TenantSchemaInitializer} to
 * pre-create a tenant's schema (when {@code holon.tenant.data.auto-create-schema} is
 * enabled — the default) before that connection init SQL is ever executed.
 *
 * <h2>MySQL is not a supported dialect</h2>
 * <p>MySQL was removed from this enum after a real Testcontainers-backed integration test
 * ({@code TenantMigrationScriptsMultiDialectTest} in {@code tenant-onboarding}) proved the
 * framework's bundled {@code V1__}/{@code V1.1__} tenant-migration scripts do not run on MySQL
 * at all — they use {@code BIGSERIAL}/{@code GENERATED BY DEFAULT AS IDENTITY}, both invalid
 * MySQL syntax (MySQL only understands {@code AUTO_INCREMENT}). Because those scripts are
 * shared as a single set across every dialect (no per-vendor script variants), and no single
 * auto-increment column syntax is valid on both PostgreSQL and MySQL simultaneously, properly
 * supporting MySQL would require restructuring the migration scripts into vendor-specific
 * variants — a real, deliberately-deferred architectural change, not a quick fix. Re-adding
 * MySQL here without first doing that restructuring will silently break tenant onboarding for
 * any application that selects it.
 */
public enum DatabaseDialect {

	/**
	 * PostgreSQL — uses {@code SET search_path TO "<schema>"}.
	 * Also compatible with CockroachDB.
	 */
	POSTGRESQL("SET search_path TO \"%s\"", "CREATE SCHEMA IF NOT EXISTS \"%1$s\""),

	/**
	 * H2 in-memory / file database — uses {@code SET SCHEMA "<schema>"}.
	 * Primarily useful for integration tests.
	 */
	H2("SET SCHEMA \"%s\"", "CREATE SCHEMA IF NOT EXISTS \"%1$s\""),

	/**
	 * Microsoft SQL Server — uses {@code USE [<schema>]}.
	 *
	 * <p>SQL Server has no {@code CREATE SCHEMA IF NOT EXISTS} shorthand, so the
	 * create-schema SQL is a guarded batch that checks {@code sys.schemas} first.
	 */
	SQLSERVER("USE [%s]",
			"IF NOT EXISTS (SELECT * FROM sys.schemas WHERE name = '%1$s') EXEC('CREATE SCHEMA [%1$s]')"),

	/**
	 * Oracle — uses {@code ALTER SESSION SET CURRENT_SCHEMA = "<schema>"}.
	 *
	 * <p>Oracle has no create-schema equivalent: a "schema" is a database user,
	 * created via {@code CREATE USER} plus privilege grants. Automatic schema
	 * creation is therefore not supported for this dialect — {@code buildCreateSchemaSql}
	 * always returns {@link Optional#empty()}, so provisioning Oracle schemas/users
	 * remains the application's/DBA's responsibility.
	 */
	ORACLE("ALTER SESSION SET CURRENT_SCHEMA = \"%s\"", null);

	private final String sqlTemplate;
	private final String createSchemaTemplate;

	DatabaseDialect(String sqlTemplate, String createSchemaTemplate) {
		this.sqlTemplate = sqlTemplate;
		this.createSchemaTemplate = createSchemaTemplate;
	}

	/**
	 * Returns the connection-initialisation SQL for the given schema name.
	 *
	 * <p>The schema name is always quoted/escaped per this dialect's identifier-quoting
	 * convention (double quotes for PostgreSQL/H2/Oracle, backticks for MySQL, brackets
	 * for SQL Server) so the exact case given is preserved. This is <strong>required</strong>
	 * for consistency with {@link #buildCreateSchemaSql(String)} and with Flyway's own
	 * schema handling (Flyway likewise quotes generated identifiers to preserve exact
	 * case): most dialects fold <em>unquoted</em> identifiers to a canonical case
	 * (H2/Oracle uppercase them, PostgreSQL lowercases them), so a plain, unquoted
	 * {@code SET SCHEMA tenant_acme} and a quoted {@code CREATE SCHEMA "tenant_acme"}
	 * would silently resolve to two <em>different</em> schema objects — exactly the bug
	 * this quoting avoids.
	 *
	 * @param schemaName unquoted schema name; must not be null
	 * @return the ready-to-execute SQL string
	 */
	public String buildInitSql(String schemaName) {
		return String.format(sqlTemplate, schemaName);
	}

	/**
	 * Returns the SQL to create the given schema if it does not already exist, or
	 * {@link Optional#empty()} if this dialect has no simple DDL equivalent (see
	 * {@link #ORACLE}).
	 *
	 * <p>Quoted per this dialect's identifier convention — see {@link #buildInitSql(String)}
	 * for why this must match.
	 *
	 * @param schemaName unquoted schema name; must not be null
	 * @return the ready-to-execute create-schema SQL, or empty if unsupported for this dialect
	 */
	public Optional<String> buildCreateSchemaSql(String schemaName) {
		return createSchemaTemplate == null
				? Optional.empty()
				: Optional.of(String.format(createSchemaTemplate, schemaName));
	}
}


